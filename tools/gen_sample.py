#!/usr/bin/env python3
"""Regenerate static/sample.js (example words per school year) from content/uk-statutory/lists.json.

Usage: python3 tools/gen_sample.py          (run from the repo root; rewrites static/sample.js)
       python3 tools/gen_sample.py --check  (writes nothing; exit 1 on drift; tests/sample_years.test.mjs runs this)
Years 1-2 use the whole common-exception-words list (45 / 64 words); years 3-6 are 100-word lists, so
the example is the first WEEK_CAP practised forms (a sensible week, not the whole list). Reception uses Year 1.
"""
import json, pathlib, sys
WEEK_CAP = 20
root = pathlib.Path(__file__).resolve().parent.parent
lists = {l["id"]: l for l in json.load(open(root / "content/uk-statutory/lists.json"))["lists"]}

def words(lid, cap=None):
    out = []
    for e in lists[lid]["entries"]:
        out += [e["official"]] if cap is None else e["forms"]
        if cap and len(out) >= cap:
            return out[:cap]
    return out

y1, y2 = words("y1-common-exception-words"), words("y2-common-exception-words")
y34, y56 = words("y3-4-word-list", WEEK_CAP), words("y5-6-word-list", WEEK_CAP)
j = lambda n, w: f"export const {n} = {json.dumps(w, indent=2)};\n"
src = (
    "// sample.js - example words per school year for the parent page (Vikunja #4632, #6335).\n"
    "// GENERATED by tools/gen_sample.py from content/uk-statutory/lists.json (National Curriculum English\n"
    "// appendix 1; Open Government Licence v3.0). tests/sample_years.test.mjs fails if this drifts. Words only.\n"
    "// Y1/Y2: whole common-exception lists. Y3-4 and Y5-6: the first 20 practised words of the statutory list.\n"
    + j("Y1_SAMPLE", y1) + j("Y2_SAMPLE", y2) + j("Y34_SAMPLE", y34) + j("Y56_SAMPLE", y56) +
    "\n/** Example words for a school year (0 = Reception, which uses the Year 1 list). */\n"
    "export function sampleForYear(year) {\n"
    "  const y = Number(year);\n"
    "  if (!Number.isFinite(y) || y <= 1) return Y1_SAMPLE; // NaN (unknown year) falls back to the gentlest list\n"
    "  if (y === 2) return Y2_SAMPLE;\n  if (y <= 4) return Y34_SAMPLE;\n  return Y56_SAMPLE;\n}\n"
)
out = root / "static/sample.js"
if "--check" in sys.argv:  # drift check: write nothing, exit 1 when sample.js differs from the generated text
    if out.read_text() != src:
        sys.exit("static/sample.js is stale: run python3 tools/gen_sample.py")
    sys.exit(0)
out.write_text(src)
